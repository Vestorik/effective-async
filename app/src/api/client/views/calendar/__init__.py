"""
Пакет представления календаря (Calendar Views).

Назначение:
    Предоставляет HTML-представление календаря с отображением событий и встреч.

    Календарь показывает дни месяца:
    - Пустые дни (до начала месяца и после конца) — белые.
    - Дни с событиями/встречами — красные.
    - Если за день несколько событий/встреч — отображается число.
    - Если одно событие/встреча — отображается название.

Архитектура:
    - calendar_views.py: эндпоинт GET /views/calendar с логикой формирования данных.
    - Шаблон: templates/pages/calendar/calendar.html (создаётся отдельно).

Ключевые принципы:
    - DRY: данные событий и встреч объединяются в единую структуру day_events.
    - KISS: логика формирования календаря в одной функции.
    - Производительность: единый запрос за все события/встречи месяца.

Ограничения:
    - Требуется аутентификация пользователя.
    - События и встречи фильтруются по текущему пользователю.

Примеры:
    # Открыть календарь на текущий месяц
    GET /views/calendar

    # Открыть календарь на конкретный месяц
    GET /views/calendar?year=2026&month=3
"""

